import type { ButtonHTMLAttributes, ReactNode } from "react";

export function cx(...parts: (string | false | null | undefined)[]): string {
  return parts.filter(Boolean).join(" ");
}

export function Eyebrow({ children, className }: { children: ReactNode; className?: string }) {
  return (
    <div
      className={cx(
        "font-mono text-[10.5px] font-medium uppercase tracking-[0.14em] text-slate-500",
        className,
      )}
    >
      {children}
    </div>
  );
}

export function PageHeader({
  index,
  section,
  title,
  description,
  actions,
  meta,
}: {
  index: string;
  section: string;
  title: ReactNode;
  description?: ReactNode;
  actions?: ReactNode;
  meta?: ReactNode;
}) {
  return (
    <header className="flex flex-wrap items-end justify-between gap-x-8 gap-y-4 border-b border-slate-800 pb-6">
      <div className="min-w-0 max-w-3xl">
        <Eyebrow>
          <span className="text-slate-400">{index}</span>
          <span className="mx-2 text-slate-700">/</span>
          {section}
        </Eyebrow>
        <h1 className="mt-3 text-[26px] font-medium leading-tight tracking-[-0.015em] text-slate-50">
          {title}
        </h1>
        {description && (
          <p className="mt-2 text-[14px] leading-relaxed text-slate-400">{description}</p>
        )}
        {meta && <div className="mt-3 flex flex-wrap items-center gap-2">{meta}</div>}
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </header>
  );
}

export function Card({
  title,
  subtitle,
  actions,
  children,
  className,
  flush,
}: {
  title?: ReactNode;
  subtitle?: ReactNode;
  actions?: ReactNode;
  children: ReactNode;
  className?: string;
  flush?: boolean;
}) {
  return (
    <section className={cx("rounded-md border border-slate-800 bg-slate-900", className)}>
      {(title || actions) && (
        <header className="flex items-start justify-between gap-4 border-b border-slate-800 px-5 py-3.5">
          <div className="min-w-0">
            {title && (
              <h2 className="text-[13.5px] font-medium tracking-[-0.005em] text-slate-100">
                {title}
              </h2>
            )}
            {subtitle && (
              <p className="mt-0.5 text-[12px] leading-snug text-slate-500">{subtitle}</p>
            )}
          </div>
          {actions && <div className="flex shrink-0 items-center gap-2">{actions}</div>}
        </header>
      )}
      <div className={flush ? undefined : "p-5"}>{children}</div>
    </section>
  );
}

type Tone = "slate" | "cyan" | "emerald" | "amber" | "rose" | "violet" | "sky";

const TONES: Record<Tone, string> = {
  slate: "border-slate-700 text-slate-300",
  cyan: "border-cyan-400/35 text-cyan-300",
  emerald: "border-emerald-400/35 text-emerald-300",
  amber: "border-amber-400/35 text-amber-300",
  rose: "border-rose-400/40 text-rose-300",
  violet: "border-violet-400/35 text-violet-300",
  sky: "border-sky-400/35 text-sky-300",
};

const DOTS: Record<Tone, string> = {
  slate: "bg-slate-500",
  cyan: "bg-cyan-400",
  emerald: "bg-emerald-400",
  amber: "bg-amber-400",
  rose: "bg-rose-400",
  violet: "bg-violet-400",
  sky: "bg-sky-400",
};

export function Badge({
  tone = "slate",
  children,
  title,
}: {
  tone?: Tone;
  children: ReactNode;
  title?: string;
}) {
  return (
    <span
      title={title}
      className={cx(
        "inline-flex h-[20px] items-center gap-1 whitespace-nowrap rounded-[3px] border px-1.5 font-mono text-[10.5px] font-medium uppercase tracking-[0.06em]",
        TONES[tone],
      )}
    >
      {children}
    </span>
  );
}

export function StatusDot({ tone = "slate", pulse }: { tone?: Tone; pulse?: boolean }) {
  return (
    <span className="relative inline-flex h-1.5 w-1.5 shrink-0">
      {pulse && (
        <span className={cx("absolute inset-0 animate-ping rounded-full opacity-60", DOTS[tone])} />
      )}
      <span className={cx("relative h-1.5 w-1.5 rounded-full", DOTS[tone])} />
    </span>
  );
}

export type Provenance =
  | "observed"
  | "ml_prediction"
  | "simulation_estimate"
  | "llm_hypothesis"
  | "verified"
  | "ground_truth"
  | "heuristic";

const PROVENANCE: Record<Provenance, { label: string; tone: Tone; help: string }> = {
  observed: { label: "Observed", tone: "sky", help: "Measured telemetry (simulated sensor)" },
  ml_prediction: {
    label: "ML model",
    tone: "violet",
    help: "Output of a trained model; probabilistic, not a measurement",
  },
  simulation_estimate: {
    label: "Simulated",
    tone: "amber",
    help: "Counterfactual digital-twin simulation under documented assumptions",
  },
  llm_hypothesis: {
    label: "LLM hypothesis",
    tone: "rose",
    help: "Generated by a language model; must be checked against evidence",
  },
  verified: {
    label: "Verified",
    tone: "emerald",
    help: "Passed the deterministic safety verifier",
  },
  ground_truth: {
    label: "Ground truth",
    tone: "slate",
    help: "Simulator internals, never shown to the models or the agent",
  },
  heuristic: { label: "Heuristic", tone: "slate", help: "Simple rule, not a statistical estimate" },
};

export function ProvenanceTag({ kind }: { kind: Provenance }) {
  const p = PROVENANCE[kind];
  return (
    <span
      title={p.help}
      className="inline-flex items-center gap-1.5 whitespace-nowrap font-mono text-[10px] font-medium uppercase tracking-[0.1em] text-slate-500"
    >
      <StatusDot tone={p.tone} />
      {p.label}
    </span>
  );
}

export function Button({
  variant = "secondary",
  className,
  ...props
}: ButtonHTMLAttributes<HTMLButtonElement> & {
  variant?: "primary" | "secondary" | "danger" | "ghost";
}) {
  return (
    <button
      {...props}
      className={cx(
        "inline-flex h-8 items-center justify-center gap-2 rounded-[5px] px-3 text-[13px] font-medium transition-colors",
        "disabled:cursor-not-allowed disabled:opacity-40 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-cyan-400/60 focus-visible:ring-offset-2 focus-visible:ring-offset-slate-950",
        variant === "primary" && "bg-slate-50 text-slate-950 hover:bg-white",
        variant === "secondary" &&
          "border border-slate-700 bg-slate-900 text-slate-100 hover:border-slate-600 hover:bg-slate-800",
        variant === "danger" &&
          "border border-rose-400/40 text-rose-300 hover:border-rose-400/70 hover:bg-rose-400/[0.08]",
        variant === "ghost" && "text-slate-400 hover:bg-slate-800/70 hover:text-slate-100",
        className,
      )}
    />
  );
}

export function Segmented<T extends string | number>({
  options,
  value,
  onChange,
  format,
}: {
  options: readonly T[];
  value: T;
  onChange: (v: T) => void;
  format?: (v: T) => ReactNode;
}) {
  return (
    <div className="inline-flex rounded-[5px] border border-slate-800 bg-slate-950 p-0.5">
      {options.map((o) => (
        <button
          key={String(o)}
          onClick={() => onChange(o)}
          className={cx(
            "h-6 rounded-[3px] px-2 font-mono text-[11px] transition-colors",
            o === value ? "bg-slate-800 text-slate-100" : "text-slate-500 hover:text-slate-300",
          )}
        >
          {format ? format(o) : String(o)}
        </button>
      ))}
    </div>
  );
}

export function Stat({
  label,
  value,
  unit,
  hint,
  provenance,
  tone,
}: {
  label: string;
  value: ReactNode;
  unit?: string;
  hint?: ReactNode;
  provenance?: Provenance;
  tone?: "ok" | "warn" | "bad";
}) {
  return (
    <div className="relative bg-slate-900 px-5 py-4">
      {tone && tone !== "ok" && (
        <span
          className={cx(
            "absolute inset-x-0 top-0 h-[2px]",
            tone === "bad" ? "bg-rose-400" : "bg-amber-400",
          )}
        />
      )}
      <div className="flex items-center justify-between gap-2">
        <Eyebrow>{label}</Eyebrow>
        {provenance && <ProvenanceTag kind={provenance} />}
      </div>
      <div
        className={cx(
          "mt-3 font-mono text-[28px] font-normal leading-none tracking-[-0.02em] tabular-nums",
          tone === "bad" ? "text-rose-300" : tone === "warn" ? "text-amber-300" : "text-slate-50",
        )}
      >
        {value}
        {unit && <span className="ml-1.5 text-[13px] tracking-normal text-slate-500">{unit}</span>}
      </div>
      {hint && <div className="mt-2.5 font-mono text-[11px] text-slate-500">{hint}</div>}
    </div>
  );
}

export function Notice({
  tone = "slate",
  children,
}: {
  tone?: "slate" | "amber" | "rose" | "cyan" | "emerald";
  children: ReactNode;
}) {
  return (
    <div
      className={cx(
        "rounded-[5px] border border-slate-800 border-l-2 bg-slate-900 px-4 py-2.5 text-[13px] leading-relaxed text-slate-300",
        tone === "slate" && "border-l-slate-500",
        tone === "amber" && "border-l-amber-400",
        tone === "rose" && "border-l-rose-400",
        tone === "cyan" && "border-l-cyan-400",
        tone === "emerald" && "border-l-emerald-400",
      )}
    >
      {children}
    </div>
  );
}

export function Spinner({ className }: { className?: string }) {
  return (
    <span
      aria-hidden
      className={cx(
        "inline-block h-3.5 w-3.5 animate-spin rounded-full border-[1.5px] border-current border-r-transparent",
        className,
      )}
    />
  );
}

export function Field({ label, children }: { label: string; children: ReactNode }) {
  return (
    <label className="flex flex-col gap-1.5">
      <Eyebrow>{label}</Eyebrow>
      {children}
    </label>
  );
}

